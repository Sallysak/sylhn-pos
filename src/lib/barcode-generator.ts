const START_CODE_B = 104;
const STOP_PATTERN = [2, 3, 3];

export function generateCode128Barcode(data: string, barHeight = 10, moduleWidth = 0.2): string {
  const patterns: number[][] = [CODE128B[START_CODE_B]];
  let checksum = START_CODE_B;
  for (let i = 0; i < data.length; i++) {
    const charCode = data.charCodeAt(i);
    const idx = charCode - 32;
    if (idx < 0 || idx >= CODE128B.length - 6) continue;
    patterns.push(CODE128B[idx]);
    checksum += (idx + 1) * (i + 1);
  }
  checksum = checksum % 103;
  if (checksum >= 0 && checksum < CODE128B.length) patterns.push(CODE128B[checksum]);
  patterns.push(STOP_PATTERN);
  let html = '<div style="display:flex;align-items:flex-end;height:' + barHeight + 'mm;">';
  let isBar = true;
  for (const pattern of patterns) {
    for (const width of pattern) {
      const w = width * moduleWidth;
      html += isBar ? `<div style="width:${w}mm;height:100%;background:#000;"></div>` : `<div style="width:${w}mm;height:100%;"></div>`;
      isBar = !isBar;
    }
  }
  html += '</div>';
  return html;
}

export function formatBarcodeText(data: string): string {
  return data.slice(0, 13);
}
